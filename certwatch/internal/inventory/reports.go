const (
	ReportInventory = "inventory"
	ReportExpiry    = "expiry"
	ReportFindings  = "findings"

	FormatMarkdown = "markdown"
	FormatCSV      = "csv"
	FormatJSON     = "json"

	sqlReportInsert = "INSERT INTO reports (kind, format, title, row_count, includes_demo, sha256, content, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)"
	sqlReportGet    = "SELECT id, kind, format, title, row_count, includes_demo, sha256, created_at, length(content), content FROM reports WHERE id = ?"
	sqlReportList   = "SELECT id, kind, format, title, row_count, includes_demo, sha256, created_at, length(content), '' FROM reports WHERE (?1 = '' OR instr(lower(title || ' ' || kind || ' ' || format), ?1) > 0) AND (?2 = 'all' OR kind = ?2) ORDER BY id DESC LIMIT ?3"
	sqlReportDelete = "DELETE FROM reports WHERE id = ?"
)

var ReportKinds = []string{ReportInventory, ReportExpiry, ReportFindings}

var ReportFormats = []string{FormatMarkdown, FormatCSV, FormatJSON}

var ReportFilters = []string{"all", ReportInventory, ReportExpiry, ReportFindings}

var reportTitles = map[string]string{
	ReportInventory: "Certificate inventory",
	ReportExpiry:    "Certificates expiring within 90 days",
	ReportFindings:  "Validation and configuration findings",
}

func ReportTitle(kind string) string {
	return reportTitles[kind]
}

type Report struct {
	ID           int64
	Kind         string
	Format       string
	Title        string
	Rows         int
	IncludesDemo bool
	SHA256       string
	CreatedAt    time.Time
	Size         int
	Content      string
}

func (r Report) FileName() string {
	extension := map[string]string{FormatMarkdown: "md", FormatCSV: "csv", FormatJSON: "json"}[r.Format]
	return fmt.Sprintf("certwatch-%s-%s.%s", r.Kind, r.CreatedAt.UTC().Format("20060102-150405"), extension)
}

func GuardCell(value string) string {
	if value != "" && strings.ContainsRune("=+-@\t\r", rune(value[0])) {
		return "'" + value
	}
	return value
}

func yesNo(value bool) string {
	if value {
		return "yes"
	}
	return "no"
}

func day(moment time.Time) string {
	return moment.UTC().Format("2006-01-02")
}

func (s *Service) reportRows(ctx context.Context, kind string, now time.Time) ([]string, [][]string, bool, error) {
	demo := false
	switch kind {
	case ReportInventory, ReportExpiry:
		list, err := s.Certificates(ctx, Query{Filter: "tracked"})
		if err != nil {
			return nil, nil, false, err
		}
		if kind == ReportInventory {
			columns := []string{"Certificate", "Issuer", "Valid from", "Valid until", "Days left", "Names", "Key", "Signature", "Used by", "Source", "Fingerprint (SHA-256)", "Demo"}
			var rows [][]string
			for _, c := range list {
				demo = demo || c.Demo
				rows = append(rows, []string{c.Name, c.Issuer, day(c.NotBefore), day(c.NotAfter), strconv.Itoa(c.DaysLeft(now)), strings.Join(c.Names, " "), fmt.Sprintf("%s %d", c.KeyAlgorithm, c.KeyBits), c.SignatureAlgorithm, c.UsedBy, c.Source, c.Fingerprint, yesNo(c.Demo)})
			}
			return columns, rows, demo, nil
		}
		columns := []string{"Certificate", "Valid until", "Days left", "State", "Used by", "Issuer", "Demo"}
		var rows [][]string
		limit := now.AddDate(0, 0, 90)
		for _, c := range list {
			if c.NotAfter.After(limit) {
				continue
			}
			demo = demo || c.Demo
			state, _ := ExpiryState(c.NotAfter, now)
			rows = append(rows, []string{c.Name, day(c.NotAfter), strconv.Itoa(c.DaysLeft(now)), state, c.UsedBy, c.Issuer, yesNo(c.Demo)})
		}
		return columns, rows, demo, nil
	case ReportFindings:
		list, err := s.Findings(ctx, 0)
		if err != nil {
			return nil, nil, false, err
		}
		columns := []string{"Endpoint", "Severity", "Finding", "Detail", "Observed", "Demo"}
		var rows [][]string
		for _, f := range list {
			demo = demo || f.Demo
			rows = append(rows, []string{f.Address, string(f.Severity), f.Code, f.Detail, f.ObservedAt.UTC().Format(time.RFC3339), yesNo(f.Demo)})
		}
		return columns, rows, demo, nil
	}
	return nil, nil, false, &ValidationError{Field: "kind", Problem: fmt.Sprintf("unknown report kind %q", kind), Fix: "Use one of: " + strings.Join(ReportKinds, ", ")}
}

func markdownCell(value string) string {
	value = strings.ReplaceAll(value, "|", "\\|")
	value = strings.ReplaceAll(value, "\n", " ")
	if value == "" {
		return "-"
	}
	return value
}

func Render(format, title string, generated time.Time, demo bool, columns []string, rows [][]string) (string, error) {
	var out bytes.Buffer
	switch format {
	case FormatMarkdown:
		fmt.Fprintf(&out, "# %s\n\n", title)
		fmt.Fprintf(&out, "Generated by CertWatch on %s. Rows: %d.\n\n", generated.UTC().Format("2006-01-02 15:04 UTC"), len(rows))
		if demo {
			out.WriteString("This report includes demo data. Demo rows are marked in the last column.\n\n")
		}
		if len(rows) == 0 {
			out.WriteString("Nothing to report.\n")
			return out.String(), nil
		}
		out.WriteString("| " + strings.Join(columns, " | ") + " |\n")
		out.WriteString("|" + strings.Repeat(" --- |", len(columns)) + "\n")
		for _, row := range rows {
			cells := make([]string, len(row))
			for i, cell := range row {
				cells[i] = markdownCell(cell)
			}
			out.WriteString("| " + strings.Join(cells, " | ") + " |\n")
		}
	case FormatCSV:
		writer := csv.NewWriter(&out)
		if err := writer.Write(columns); err != nil {
			return "", err
		}
		for _, row := range rows {
			cells := make([]string, len(row))
			for i, cell := range row {
				cells[i] = GuardCell(cell)
			}
			if err := writer.Write(cells); err != nil {
				return "", err
			}
		}
		writer.Flush()
		if err := writer.Error(); err != nil {
			return "", err
		}
	case FormatJSON:
		items := make([]map[string]string, 0, len(rows))
		for _, row := range rows {
			item := map[string]string{}
			for i, cell := range row {
				item[columns[i]] = cell
			}
			items = append(items, item)
		}
		document := struct {
			Title        string              `json:"title"`
			GeneratedAt  string              `json:"generated_at"`
			IncludesDemo bool                `json:"includes_demo"`
			Columns      []string            `json:"columns"`
			Rows         []map[string]string `json:"rows"`
		}{title, generated.UTC().Format(time.RFC3339), demo, columns, items}
		encoded, err := json.MarshalIndent(document, "", "  ")
		if err != nil {
			return "", err
		}
		out.Write(encoded)
		out.WriteByte('\n')
	default:
		return "", &ValidationError{Field: "format", Problem: fmt.Sprintf("unknown report format %q", format), Fix: "Use one of: " + strings.Join(ReportFormats, ", ")}
	}
	return out.String(), nil
}

func (s *Service) GenerateReport(ctx context.Context, kind, format string) (Report, error) {
	now := s.now()
	columns, rows, demo, err := s.reportRows(ctx, kind, now)
	if err != nil {
		return Report{}, err
	}
	content, err := Render(format, ReportTitle(kind), now, demo, columns, rows)
	if err != nil {
		return Report{}, err
	}
	sum := sha256.Sum256([]byte(content))
	report := Report{Kind: kind, Format: format, Title: ReportTitle(kind), Rows: len(rows), IncludesDemo: demo, SHA256: hex.EncodeToString(sum[:]), CreatedAt: now.UTC().Truncate(time.Second), Size: len(content), Content: content}
	err = s.inTx(ctx, func(tx *sql.Tx) error {
		result, err := tx.ExecContext(ctx, sqlReportInsert, kind, format, report.Title, report.Rows, flag(demo), report.SHA256, content, stamp(now))
		if err != nil {
			return err
		}
		report.ID, err = result.LastInsertId()
		return err
	})
	return report, err
}

func scanReport(row scanner) (Report, error) {
	var r Report
	var created string
	err := row.Scan(&r.ID, &r.Kind, &r.Format, &r.Title, &r.Rows, &r.IncludesDemo, &r.SHA256, &created, &r.Size, &r.Content)
	if errors.Is(err, sql.ErrNoRows) {
		return r, ErrNotFound
	}
	r.CreatedAt = parseTime(created)
	return r, err
}

func (s *Service) Report(ctx context.Context, id int64) (Report, error) {
	return scanReport(s.db.QueryRowContext(ctx, sqlReportGet, id))
}

func (s *Service) Reports(ctx context.Context, query Query) ([]Report, error) {
	filter, err := pick(query.Filter, ReportFilters)
	if err != nil {
		return nil, err
	}
	rows, err := s.db.QueryContext(ctx, sqlReportList, query.search(), filter, query.limit())
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var list []Report
	for rows.Next() {
		report, err := scanReport(rows)
		if err != nil {
			return nil, err
		}
		list = append(list, report)
	}
	return list, rows.Err()
}

func (s *Service) DeleteReport(ctx context.Context, id int64) error {
	return s.inTx(ctx, func(tx *sql.Tx) error {
		result, err := tx.ExecContext(ctx, sqlReportDelete, id)
		if err != nil {
			return err
		}
		if count, _ := result.RowsAffected(); count == 0 {
			return ErrNotFound
		}
		return nil
	})
}
